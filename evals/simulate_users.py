def _reid_plan(plan: dict, owner_id: str) -> dict:
    """Same id scheme as DemoGateway.telegram_user, so a copied plan never shares ids with its source."""
    plan = copy.deepcopy(plan)
    plan["id"] = str(uuid.uuid5(uuid.NAMESPACE_URL, f"plan:{owner_id}"))
    for d in plan["days"]:
        d["id"] = str(uuid.uuid5(uuid.NAMESPACE_URL, f"day:{owner_id}:{d['day_index']}"))
        for i, e in enumerate(d["exercises"]):
            e["id"] = str(uuid.uuid5(uuid.NAMESPACE_URL, f"wex:{owner_id}:{d['day_index']}:{i}"))
    return plan


async def seed_clients(db_path: Path, runs: list[tuple[Persona, str]]) -> dict[str, str]:
    """One demo client per dialog in the SERVICE's SQLite, via the gateway's own per-tester copy. → tg id → user id."""
    from tulpar_ai.gateway.demo import DemoGateway
    from tulpar_ai.store import Store

    store = await Store(db_path).open()
    try:
        if await store.demo_user_count() == 0:
            raise SystemExit(f"{db_path}: no demo users — is the service running with this AI_DATA_DIR?")
        gw = DemoGateway(store)
        home_src = json.loads((ROOT / "fixtures" / "demo.json").read_text(encoding="utf-8"))["clients"][1]["active_plan"]
        out = {}
        for p, tg in runs:
            u = await gw.telegram_user(tg, f"{p.name} (синт.)", as_trainer=False)
            row = await store.demo_user(u.id)
            profile = {**row["profile"], **p.profile}
            if p.trainer_note is not None:
                profile["trainer_note"] = p.trainer_note
            await store.upsert_demo_user({**row, "profile": profile})
            if p.home_plan:
                await store.put_demo_plan(u.id, _reid_plan(home_src, u.id))
            out[tg] = u.id
        return out
    finally:
        await store.close()


