"""Synthetic user simulation: LLM personas talk to a RUNNING service through its public HTTP API.

    .venv/bin/python evals/simulate_users.py --base http://localhost:8095 --sim-db data/sim/app.sqlite

NOT REAL USERS. Every client and the trainer here are LLM personas (kimi-k2.6, fallback deepseek-v4.1-flash —
never minimax-m3, the product's own model). Their messages, 👍/👎 and reasons are generated by a model: this is
a behavioural test of the product, not customer feedback, and its numbers must never be presented as feedback
from people. Every rating comment sent through the feedback API starts with «[симуляция]», every escalation
reply of the trainer persona too; sim accounts are named «… (синт.)» and have telegram_id `sim-…`.

How it works
  1. Accounts. With --sim-db (local service only) every client persona gets its OWN demo client, created with
     DemoGateway.telegram_user — the code path that gives each new Telegram tester a personal copy of the demo
     client — and then its profile (and, for home personas, the plan) is adjusted to the persona. The script acts
     as these clients with the service's internal credential (X-Internal-Secret + X-Act-As, as the MCP server
     does; the secret is read from settings and never printed). POST /api/auth/telegram cannot create clients
     here: it needs the bot token and Telegram-signed initData, and the local run has no bot.
     Without --sim-db the two fixture demo clients are reused round-robin.
  2. Clients. Each persona has a goal and a scenario of 4–6 beats. The persona LLM writes the next message from
     the beat + the dialogue so far; the service answers (/api/chat); the persona LLM rates the reply (up/down +
     one-line reason, by a fixed rubric) and the rating goes through POST /api/messages/{id}/feedback. Meal cards
     are confirmed as a user pressing «Записать» would. A beat marked voice is sent as a real voice note
     (edge-tts → /api/chat audio → the service's speech-to-text).
  3. Trainer. After the clients a trainer persona reads /api/queue and handles every item of THIS run: program
     drafts (accept only with no validator errors and a draft that matches the request; otherwise edit with a
     comment once, then accept or reject) and escalations (short reply + a verdict whether it was justified).
  4. Metrics → --out (JSON): intents, kinds, answered rate on questions, escalations and their verdicts, simulated
     👍 rate overall and per persona, latency p50/p95, answer-cache hits (from the service's LangSmith project,
     when reachable), trainer decisions, automatically collected problems and the full transcripts.

Budget: at most --max-persona-turns persona turns in total (client messages + trainer decisions), all calls are
sequential, a 429 is answered with a pause and a retry. The persona LLM calls of THIS process are not traced
(LANGSMITH_TRACING=false below), so LangSmith only has the product's own runs in the service's project.
"""

