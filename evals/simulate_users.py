def plan_runs(n: int, rng: random.Random, only: list[str] | None, tag: str = "") -> list[tuple[Persona, str, str]]:
    pool = [p for p in PERSONAS if not only or p.key in only]
    if not pool:
        raise SystemExit(f"no personas match {only}; known: {', '.join(p.key for p in PERSONAS)}")
    order = rng.sample(pool, len(pool))
    runs = []
    for i in range(n):
        p = order[i % len(order)]
        k = i // len(order)
        label = p.key if k == 0 else f"{p.key}-{k + 1}"
        runs.append((p, label, f"sim-{tag + '-' if tag else ''}{label}"))
    return runs


async def run(args) -> dict:
    s = get_settings()
    host = urlparse(args.base).hostname or ""
    # Synthetic 👍/👎 must never land next to real feedback: local services only, and a «-sim» LangSmith project.
    if host not in LOCAL_HOSTS:
        raise SystemExit("the simulator posts synthetic ratings: run it against a local service only (localhost)")
    if not args.no_langsmith and not str(args.langsmith_project).endswith("-sim"):
        raise SystemExit("--langsmith-project must end with '-sim' so synthetic ratings stay out of the real project")
    rng = random.Random(args.seed)
    runs = plan_runs(args.dialogs, rng, [x.strip() for x in args.personas.split(",")] if args.personas else None,
                     tag=args.tag)
    started = datetime.now(timezone.utc) - timedelta(seconds=2)
    t0 = time.perf_counter()
    async with httpx.AsyncClient(base_url=args.base, timeout=180) as http:
        api = Api(http)
        health = await api.json("GET", "/health")
        sim = Simulation(api, PersonaLLM(PERSONA_MODELS), Budget(args.max_persona_turns), tts_ok=not args.no_voice)
        print(f"{NOTICE}\nСервис {args.base} (режим {health.get('mode')}), диалогов {len(runs)}, seed {args.seed}")

        accounts, headers_of = "", {}
        if args.sim_db:
            if host not in LOCAL_HOSTS:
                raise SystemExit("--sim-db writes to the service's SQLite: only for a local service (localhost)")
            ids = await seed_clients(Path(args.sim_db), [(p, tg) for p, _, tg in runs])
            for p, label, tg in runs:
                h = {"X-Internal-Secret": s.internal_secret, "X-Act-As": ids[tg]}
                me = await api.call("GET", "/api/me", h)
                if me.status_code != 200 or me.json().get("id") != ids[tg]:
                    raise SystemExit(f"the service does not see sim client {label} ({me.status_code}): wrong --sim-db "
                                     "or a different INTERNAL_SECRET")
                headers_of[label] = h
                sim.client_ids[ids[tg]] = label
            accounts = ("distinct: one demo client per dialog, created in the service's SQLite with "
                        "DemoGateway.telegram_user (the per-Telegram-tester copy) and adjusted to the persona; "
                        "requests via X-Internal-Secret + X-Act-As")
        else:
            d = await api.json("POST", "/api/auth/demo-login", json={"role": "client"})
            pool = [({"Authorization": f"Bearer {d['token']}"}, d["user"]["id"])]
            second = "e9d058b1-54b9-5392-b261-f20c84f886ff"  # demo-student-2 from fixtures/demo.json
            h2 = {"X-Internal-Secret": s.internal_secret, "X-Act-As": second}
            if (await api.call("GET", "/api/me", h2)).status_code == 200:
                pool.append((h2, second))
            for i, (p, label, _) in enumerate(runs):
                headers_of[label], cid = pool[i % len(pool)]
                sim.client_ids.setdefault(cid, label)
            accounts = f"reused {len(pool)} fixture demo client(s) round-robin (no --sim-db)"
        print(f"Аккаунты: {accounts}")
        d = await api.json("POST", "/api/auth/demo-login", json={"role": "trainer"})
        trainer_h = {"Authorization": f"Bearer {d['token']}"}
        for cid in sim.client_ids:
            try:
                ctx = await api.json("GET", f"/api/trainer/clients/{cid}/context", trainer_h)
                sim.notes[cid] = ctx.get("trainer_note")
            except RuntimeError:
                sim.notes[cid] = None

        for p, label, _ in runs:
            print(f"Клиент-персона «{label}» ({p.name}): {p.goal}")
            await sim.dialog(p, label, headers_of[label], args.turns)
        print("Тренер-персона разбирает очередь")
        await sim.trainer_phase(trainer_h)
    ended = datetime.now(timezone.utc) + timedelta(seconds=2)
    n_q = sum(1 for t in sim.turns if t.get("intent") == "question")
    cache = cache_hits(args.langsmith_project, started, ended, n_q) if not args.no_langsmith else {"visible": False, "why": "--no-langsmith"}
    meta = {"started": started.isoformat(timespec="seconds"), "duration_s": round(time.perf_counter() - t0, 1),
            "base": args.base, "seed": args.seed, "dialogs_requested": args.dialogs, "max_turns_per_dialog": args.turns,
            "max_persona_turns": args.max_persona_turns, "persona_models": [m for _, m in PERSONA_MODELS],
            "product_model_not_used_for_personas": PRODUCT_MODEL, "accounts": accounts,
            "service_langsmith_project": args.langsmith_project,
            "seed_note": "seed picks the order/subset of personas; LLM sampling itself is not seeded"}
    return metrics(sim, meta, cache)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--base", default="http://localhost:8095", help="URL запущенного сервиса (локального)")
    ap.add_argument("--sim-db", default="", help="SQLite сервиса (AI_DATA_DIR/app.sqlite) — отдельный клиент на диалог")
    ap.add_argument("--dialogs", type=int, default=len(PERSONAS), help="число клиентских диалогов")
    ap.add_argument("--turns", type=int, default=6, help="максимум реплик клиента в одном диалоге")
    ap.add_argument("--max-persona-turns", type=int, default=40, help="общий бюджет: реплики клиентов + решения тренера")
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--personas", default="", help="через запятую: " + ",".join(p.key for p in PERSONAS))
    ap.add_argument("--tag", default="", help="метка аккаунтов: telegram_id sim-<tag>-<persona> (отдельные аккаунты на прогон)")
    ap.add_argument("--no-voice", action="store_true", help="голосовые пункты отправлять текстом")
    ap.add_argument("--no-langsmith", action="store_true", help="не считать попадания в кэш по LangSmith")
    ap.add_argument("--langsmith-project", default="tulpar-ai-coach-sim", help="LangSmith-проект СЕРВИСА")
    ap.add_argument("--out", default=str(ROOT / "evals" / "results" / "user_sim.json"))
    args = ap.parse_args()
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(line_buffering=True)  # progress stays visible when the output goes to a file

    res = asyncio.run(run(args))
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(res, ensure_ascii=False, indent=2), encoding="utf-8")
    fb, lat = res["simulated_feedback"], res["latency_s"]
    print(f"\n{NOTICE}\nДиалогов {res['dialogs']}, сообщений {res['client_messages']} (ошибок "
          f"{res['client_messages'] - res['client_messages_ok']}), kinds {res['kinds']}")
    print(f"Симулированные 👍 {fb['up']}/{fb['rated']} ({fb['up_pct']}%), задержка p50 {lat['p50']} с, p95 {lat['p95']} с; "
          f"решения тренера-персоны {res['trainer']['decisions']}; проблем {len(res['problems'])}")
    print(f"→ {out}")
    return 0


