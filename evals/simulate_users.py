def dialogue_text(history: list[tuple[str, str]], limit: int = 8) -> str:
    if not history:
        return "(диалог пока пуст)"
    return "\n".join(f"{'Клиент' if r == 'user' else 'Коуч'}: {short(t, 700)}" for r, t in history[-limit:])


def next_task(beat: Beat | None) -> str:
    if beat is None:
        return 'Следующей реплики не будет: "next_message": "".'
    voice = (" Это голосовое сообщение: пиши так, как человек говорит вслух, без смайликов и списков."
             if beat.voice else "")
    return f"Напиши следующую реплику клиента. Пункт сценария: {beat.goal}.{voice}"


def rating_prompt(history: list[tuple[str, str]], turn: dict, nxt: Beat | None) -> str:
    kind = turn.get("kind") or "error"
    extra = []
    if turn.get("citations_n"):
        extra.append(f"со ссылками на источники: {turn['citations_n']}")
    if turn.get("transcript"):
        extra.append(f"голосовое распознано как «{short(turn['transcript'], 200)}»")
    head = f"Последний ответ коуча — тип «{KIND_RU.get(kind, kind)}»" + (f" ({'; '.join(extra)})" if extra else "")
    esc = ("Коуч передал сообщение тренеру: в escalation_justified укажи true/false — было ли это оправдано."
           if kind == "escalated" else "escalation_justified: null.")
    return (f"Диалог (последние реплики):\n{dialogue_text(history)}\n\n{head}.\n\n"
            f"Задача 1 — оцени последний ответ коуча по правилам. {esc}\nЗадача 2 — {next_task(nxt)}\n\n"
            'Верни JSON: {"rating": "up"|"down", "reason": "одна строка, почему", "issue": "none|unsafe|wrong|'
            'unhelpful|misunderstood|unnecessary_escalation|other", "escalation_justified": true|false|null, '
            '"next_message": "..."}')


def first_prompt(beat: Beat) -> str:
    return f"Диалог пока пуст. {next_task(beat)}\n\nВерни JSON: {{\"next_message\": \"...\"}}"


