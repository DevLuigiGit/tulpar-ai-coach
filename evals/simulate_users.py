# ── small helpers ────────────────────────────────────────────────────────────
def short(text: str | None, n: int = 160) -> str:
    t = " ".join((text or "").split())
    return t if len(t) <= n else t[: n - 1] + "…"


def pct(a: int, b: int) -> float | None:
    return round(100.0 * a / b, 1) if b else None


def p95(values: list[float]) -> float | None:
    if not values:
        return None
    s = sorted(values)
    return round(s[max(0, math.ceil(0.95 * len(s)) - 1)], 2)


def p50(values: list[float]) -> float | None:
    return round(statistics.median(values), 2) if values else None


class Budget:
    def __init__(self, limit: int):
        self.limit, self.used = limit, 0

    def take(self) -> bool:
        if self.used >= self.limit:
            return False
        self.used += 1
        return True


class PersonaLLM:
    """JSON calls to the persona models (never the product's model), with retries and usage stats."""

    def __init__(self, models: list[tuple[str, str]]):
        self.models = models
        self.calls = 0
        self.failures = 0
        self.by_model: Counter = Counter()
        self.ms: list[int] = []

    async def ask(self, system: str, user: str, temperature: float = 0.6, max_tokens: int = 400) -> dict:
        delays = [3, 10, 25]
        for attempt in range(len(delays) + 1):
            try:
                self.calls += 1
                data, res = await llm.json_call("judge", system, user, temperature=temperature,
                                                max_tokens=max_tokens, models=self.models)
                self.by_model[res.model] += 1
                self.ms.append(res.latency_ms)
                return data
            except Exception as e:  # all persona models failed (429 / 5xx / bad JSON) → pause and retry
                self.failures += 1
                if attempt == len(delays):
                    raise RuntimeError(f"persona LLM failed: {short(str(e), 200)}")
                await asyncio.sleep(delays[attempt])
        return {}


class Api:
    """The service's public API with retries on 429 and transient 5xx."""

    def __init__(self, http: httpx.AsyncClient):
        self.http = http
        self.retries_429 = 0

    async def call(self, method: str, path: str, headers: dict | None = None, **kw) -> httpx.Response:
        for attempt in range(6):
            try:
                r = await self.http.request(method, path, headers=headers, **kw)
            except httpx.TransportError:
                if attempt >= 2:
                    raise
                await asyncio.sleep(5 * (attempt + 1))
                continue
            if r.status_code == 429:
                self.retries_429 += 1
                wait = float(r.headers.get("Retry-After") or 5 * 2 ** attempt)
                await asyncio.sleep(min(wait, 60))
                continue
            if r.status_code in (502, 503, 504) and attempt < 2:
                await asyncio.sleep(5 * (attempt + 1))
                continue
            return r
        return r

    async def json(self, method: str, path: str, headers: dict | None = None, **kw):
        r = await self.call(method, path, headers, **kw)
        if r.status_code >= 400:
            raise RuntimeError(f"{method} {path} → {r.status_code}: {short(r.text, 200)}")
        return r.json()


